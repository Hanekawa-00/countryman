    val worksWith: String,
) {
    fun resetFailed(message: String?) = "$resetFailedPrefix${message.orEmpty()}"
    fun saveFailed(message: String?) = "$saveFailedPrefix${message.orEmpty()}"
    fun writeDialogMessage(slot: Int) = writeDisplayNumberDescriptionTemplate.replace("%d", slot.toString())

    fun selectSimSummary(slot: Int, carrierName: String) = when (appTitle) {
        "Countryman" -> "SIM $slot · $carrierName"
        else -> "SIM $slot · $carrierName"
    }

    fun imsNumber(value: String?) = if (value.isNullOrBlank()) {
        "$imsNumberPrefix  $imsNumberUnavailable"
    } else {
        "$imsNumberPrefix  $value"
    }
}

